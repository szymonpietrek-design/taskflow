<?php

namespace App\Http\Controllers\Admin;

use App\Http\Controllers\Controller;
use App\Models\GitHubAppSetting;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\DB;
use Illuminate\Validation\ValidationException;
use Inertia\Inertia;
use Inertia\Response;

class GitHubAppSettingsController extends Controller
{
    public function index(): Response
    {
        $settings = GitHubAppSetting::current();

        return Inertia::render('admin/GitHub', [
            // Never serialize the settings model: its secret belongs on the server.
            'settings' => [
                'app_id' => $settings?->app_id === null ? '' : (string) $settings->app_id,
                'has_private_key' => $settings !== null,
                'updated_at' => $settings?->updated_at?->toIso8601String(),
            ],
        ]);
    }

    public function store(Request $request): RedirectResponse
    {
        $settings = GitHubAppSetting::current();

        $validated = $request->validate([
            'app_id' => ['required', 'integer', 'min:1'],
            'private_key' => [$settings ? 'nullable' : 'required', 'file', 'max:32'],
        ]);

        $pem = null;
        $file = $request->file('private_key');
        if ($file instanceof UploadedFile) {
            $pem = $file->get();
            $parsed = $pem === false ? false : openssl_pkey_get_private($pem);
            $details = $parsed === false ? false : openssl_pkey_get_details($parsed);

            if ($details === false || ($details['type'] ?? null) !== OPENSSL_KEYTYPE_RSA
                || ($details['bits'] ?? 0) < 2048) {
                throw ValidationException::withMessages([
                    'private_key' => 'Provide a valid RSA private key (.pem) generated by your GitHub App.',
                ]);
            }
        }

        DB::transaction(function () use ($validated, $pem, $request): void {
            $settings = GitHubAppSetting::query()->lockForUpdate()->find(1);
            if ($settings === null) {
                if ($pem === null) {
                    throw ValidationException::withMessages(['private_key' => 'A GitHub App private key is required.']);
                }
                $settings = new GitHubAppSetting();
                $settings->id = 1;
            }

            $settings->app_id = (int) $validated['app_id'];
            if ($pem !== null) {
                $settings->private_key = $pem;
            }
            $settings->updated_by = $request->user()->id;
            $settings->save();
        });

        Inertia::flash('toast', ['type' => 'success', 'message' => 'GitHub App settings saved.']);

        return to_route('admin.github.index');
    }
}
